#!/usr/bin/env tsx
/**
 * Reads the outcome records in `evidence/outcomes/` and reports whether the AQI
 * relates to anything that actually happened.
 *
 *   npm run calibrate                 # report to stdout
 *   npm run calibrate -- --write      # also write evidence/benchmarks/calibration.md
 *
 * This script's most likely output, for a long time, is "no correlation is
 * reported, n is too small". That is not a bug and it must not be papered over:
 * the moment this file prints a confident rho, someone will quote it without the
 * interval, and the interval is the only part that is honest.
 *
 * Records are JSONL, one object per line, in `evidence/outcomes/records.jsonl`.
 * The format is documented in `evidence/outcomes/README.md`. Nothing is inferred:
 * a record with no outcome is not a zero, and a missing horizon is not assumed.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { calibrate, type CalibrationRecord } from '../packages/core/src/evals/calibration.js';

const PATH = 'evidence/outcomes/records.jsonl';

function load(): { records: CalibrationRecord[]; rejected: string[] } {
  if (!existsSync(PATH)) return { records: [], rejected: [`${PATH} does not exist yet`] };
  const records: CalibrationRecord[] = [];
  const rejected: string[] = [];
  const lines = readFileSync(PATH, 'utf8').split('\n');
  lines.forEach((line, i) => {
    const t = line.trim();
    if (!t || t.startsWith('//') || t.startsWith('#')) return;
    try {
      const r = JSON.parse(t) as Partial<CalibrationRecord>;
      // Strict on purpose. A record missing a field is rejected with a reason
      // rather than defaulted, because a defaulted outcome is a fabricated one.
      const missing = (['aqi', 'aqiVersion', 'outcome', 'outcomeUnit', 'label', 'horizonDays'] as const).filter(
        (k) => r[k] === undefined || r[k] === null,
      );
      if (missing.length) {
        rejected.push(`line ${i + 1}: missing ${missing.join(', ')} — rejected rather than defaulted`);
        return;
      }
      records.push({ outcomeDefinedBy: 'submitter', ...r } as CalibrationRecord);
    } catch (err) {
      rejected.push(`line ${i + 1}: not valid JSON (${(err as Error).message})`);
    }
  });
  return { records, rejected };
}

function main(): number {
  const { records, rejected } = load();
  const report = calibrate(records);

  const lines: string[] = [
    '# Does the AQI relate to what happens?',
    '',
    '> Generated by `npm run calibrate`. Every number here is computed from records in',
    '> `evidence/outcomes/`. Nothing is estimated, modelled, or filled in.',
    '',
    `**Records: ${report.n}.**`,
    '',
    '## Conclusion',
    '',
    report.conclusion,
    '',
    '## By stratum',
    '',
    '| Stratum | n | rho | Note |',
    '|---|---|---|---|',
    ...report.strata.map((s) => `| ${s.name} | ${s.n} | ${s.rho === null ? 'not computed' : s.rho.toFixed(3)} | ${s.note} |`),
    '',
  ];

  if (report.sampleProblems.length) {
    lines.push('## Problems with this sample', '', ...report.sampleProblems.map((p) => `- ${p}`), '');
  }
  if (rejected.length) {
    lines.push('## Records rejected', '', ...rejected.map((r) => `- ${r}`), '');
  }
  lines.push(
    '## What would change this',
    '',
    ...report.whatWouldChangeThis.map((w) => `- ${w}`),
    '',
    '---',
    '',
    '*A correlation computed on self-selected reported outcomes is an observation about',
    'the people who report, not about launches in general. It is printed here anyway',
    'because the alternative — only publishing numbers that flatter the tool — is the',
    'failure mode this project exists to name.*',
  );

  const md = lines.join('\n');
  process.stdout.write(md + '\n');

  if (process.argv.includes('--write')) {
    mkdirSync('evidence/benchmarks', { recursive: true });
    writeFileSync('evidence/benchmarks/calibration.md', md + '\n', 'utf8');
    console.error('\nwrote evidence/benchmarks/calibration.md');
  }
  return 0;
}

process.exit(main());
