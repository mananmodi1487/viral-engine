#!/usr/bin/env tsx
/**
 * Runs the evaluation harness against the published dataset and writes the
 * results into evidence/benchmarks/ alongside the dataset itself.
 *
 * Usage: npm run bench
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { runEval, metricsTable, type EvalCase } from '../packages/core/src/evals/harness.js';

const raw = readFileSync('fixtures/eval-dataset.jsonl', 'utf8');
const cases: EvalCase[] = raw
  .split('\n')
  .filter((l) => l.trim() && !l.trim().startsWith('//'))
  .map((l) => JSON.parse(l) as EvalCase);

const report = runEval(cases);

const byDifficulty = (d: string): { total: number; passed: number } => {
  const subset = report.failures.concat(report.knownMisses);
  const total = cases.filter((c) => c.difficulty === d).length;
  const failedIds = new Set(report.failures.map((f) => f.id));
  return { total, passed: total - cases.filter((c) => c.difficulty === d && failedIds.has(c.id)).length };
};

const md = `# Evaluation results

Generated by \`npm run bench\` from \`fixtures/eval-dataset.jsonl\`.
Reproduce with \`npx tsx scripts/run-eval.ts\`.

**${report.passed}/${report.cases} cases passed** (${(report.passRate * 100).toFixed(1)}%).
Macro precision **${report.macro.precision.toFixed(3)}**, macro recall **${report.macro.recall.toFixed(3)}**,
F1 **${report.macro.f1.toFixed(3)}**, false-positive rate **${report.macro.falsePositiveRate.toFixed(3)}**.

| Difficulty | Cases | Passed |
|---|---:|---:|
| easy | ${byDifficulty('easy').total} | ${byDifficulty('easy').passed} |
| medium | ${byDifficulty('medium').total} | ${byDifficulty('medium').passed} |
| hard | ${byDifficulty('hard').total} | ${byDifficulty('hard').passed} |

## Per-target metrics

${metricsTable(report)}

## Every case the engine got wrong

${report.failures.length === 0 ? '_None._' : report.failures.map((f) => `
### \`${f.id}\` (${f.difficulty})

- **Why this case exists:** ${f.rationale}
- **Expected:** ${f.expected.join(', ') || '(none)'}
- **Must not fire:** ${f.mustNot.join(', ') || '(none)'}
- **Missed:** ${f.falseNegatives.join(', ') || '(none)'}
- **Wrongly fired:** ${f.falsePositives.join(', ') || '(none)'}
`).join('\n')}

## Known misses, kept in the dataset on purpose

${report.knownMisses.length === 0 ? '_None._' : report.knownMisses.map((f) => `
### \`${f.id}\`

${f.knownMiss}

- Missed: ${f.falseNegatives.join(', ') || '(none)'}
- Wrongly fired: ${f.falsePositives.join(', ') || '(none)'}
`).join('\n')}

## Limitations

A precision number with no limitations section is a marketing claim. Read these
before quoting anything above.

${report.limitations.map((l) => `- ${l}`).join('\n')}

## Dataset

\`\`\`
${cases.map((c) => `${c.id.padEnd(24)} ${c.difficulty.padEnd(7)} expect: ${c.expect.join(',') || '—'}`).join('\n')}
\`\`\`
`;

writeFileSync('evidence/benchmarks/aqi-detector-results.md', md);
writeFileSync('evidence/benchmarks/aqi-detector-results.json', JSON.stringify(report, null, 2));

console.log(`cases:  ${report.cases}`);
console.log(`passed: ${report.passed} (${(report.passRate * 100).toFixed(1)}%)`);
console.log(`macro:  precision ${report.macro.precision} · recall ${report.macro.recall} · F1 ${report.macro.f1} · FPR ${report.macro.falsePositiveRate}`);
if (report.failures.length) {
  console.log('\nfailures (published, not hidden):');
  for (const f of report.failures) {
    console.log(`  ${f.id}: missed [${f.falseNegatives.join(',')}] wrong [${f.falsePositives.join(',')}]`);
  }
}
if (report.knownMisses.length) {
  console.log('\nknown misses:');
  for (const f of report.knownMisses) console.log(`  ${f.id}: ${f.knownMiss}`);
}
console.log('\nwrote evidence/benchmarks/aqi-detector-results.{md,json}');
